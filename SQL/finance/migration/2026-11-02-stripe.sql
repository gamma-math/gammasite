-- Adds Stripe source transactions to the finance database and links derived
-- postings to their Stripe source row.

BEGIN;

CREATE TABLE IF NOT EXISTS public.stripe (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    balance_transaction_id text NOT NULL,
    payout_id text,
    date date,
    available_date date,
    payout_date date,
    amount numeric(14, 2) NOT NULL,
    fee numeric(14, 2) NOT NULL DEFAULT 0,
    net numeric(14, 2) NOT NULL,
    currency text NOT NULL,
    transaction_type text,
    reporting_category text,
    source_id text,
    payment_intent_id text,
    description text,
    user_id text,
    payer_name text,
    receipt_url text,
    is_manual boolean NOT NULL DEFAULT false,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT stripe_pkey PRIMARY KEY (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_stripe_balance_transaction_id
ON public.stripe (balance_transaction_id)
WHERE is_manual = false;

ALTER TABLE public.posteringer
    ADD COLUMN IF NOT EXISTS stripe_key bigint;

ALTER TABLE public.stripe
    ADD COLUMN IF NOT EXISTS user_id text,
    ADD COLUMN IF NOT EXISTS payer_name text,
    ADD COLUMN IF NOT EXISTS receipt_url text;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'posteringer_stripe_fk'
          AND conrelid = 'public.posteringer'::regclass
    ) THEN
        ALTER TABLE public.posteringer
            ADD CONSTRAINT posteringer_stripe_fk
            FOREIGN KEY (stripe_key)
            REFERENCES public.stripe(id)
            ON UPDATE NO ACTION
            ON DELETE NO ACTION;
    END IF;
END $$;

COMMIT;
